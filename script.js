startBtn.addEventListener("click", startTest);

function startTest() {

    startScreen.classList.add("hidden");

    examScreen.classList.remove("hidden");

    resultScreen.classList.add("hidden");

    reviewScreen.classList.add("hidden");

    currentQuestion = 0;

    userAnswers = new Array(questions.length).fill(null);

    timeLeft = 60 * 60;

    displayQuestion();

    startTimer();
}


/* =========================================================
   DISPLAY QUESTION
========================================================= */

function displayQuestion() {

    const q = questions[currentQuestion];

    questionNumber.textContent =
        `Question ${currentQuestion + 1} of ${questions.length}`;

    subjectName.textContent = q.subject;

    const progress =
        ((currentQuestion + 1) / questions.length) * 100;

    progressBar.style.width = progress + "%";

    let html = `
        <div class="question-number">
            Question ${currentQuestion + 1}
        </div>

        <h2 class="question">
            ${q.question}
        </h2>

        <div class="options">
    `;

    q.options.forEach((option, index) => {

        const checked =
            userAnswers[currentQuestion] === index
                ? "checked"
                : "";

        html += `
            <label class="option">
                <input
                    type="radio"
                    name="answer"
                    value="${index}"
                    ${checked}>
                ${option}
            </label>
        `;
    });

    html += `</div>`;

    questionContainer.innerHTML = html;

    document
        .querySelectorAll('input[name="answer"]')
        .forEach(input => {

            input.addEventListener("change", function () {

                userAnswers[currentQuestion] =
                    Number(this.value);

            });

        });

    previousBtn.disabled = currentQuestion === 0;

    if (currentQuestion === questions.length - 1) {

        nextBtn.classList.add("hidden");

        submitBtn.classList.remove("hidden");

    } else {

        nextBtn.classList.remove("hidden");

        submitBtn.classList.add("hidden");

    }
}


/* =========================================================
   NEXT BUTTON
========================================================= */

nextBtn.addEventListener("click", function () {

    if (currentQuestion < questions.length - 1) {

        currentQuestion++;

        displayQuestion();

        window.scrollTo(0, 0);
    }

});


/* =========================================================
   PREVIOUS BUTTON
========================================================= */

previousBtn.addEventListener("click", function () {

    if (currentQuestion > 0) {

        currentQuestion--;

        displayQuestion();

        window.scrollTo(0, 0);
    }

});


/* =========================================================
   TIMER
========================================================= */

function startTimer() {

    clearInterval(timerInterval);

    updateTimer();

    timerInterval = setInterval(function () {

        timeLeft--;

        updateTimer();

        if (timeLeft <= 0) {

            clearInterval(timerInterval);

            submitTest();

        }

    }, 1000);
}


function updateTimer() {

    const minutes =
        Math.floor(timeLeft / 60);

    const seconds =
        timeLeft % 60;

    timer.textContent =
        `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;
}


/* =========================================================
   SUBMIT TEST
========================================================= */

submitBtn.addEventListener("click", submitTest);

function submitTest() {

    clearInterval(timerInterval);

    let correct = 0;
    let unanswered = 0;

    const subjectStats = {};

    questions.forEach((q, index) => {

        if (!subjectStats[q.subject]) {

            subjectStats[q.subject] = {
                correct: 0,
                total: 0
            };

        }

        subjectStats[q.subject].total++;

        if (userAnswers[index] === null) {

            unanswered++;

        } else if (userAnswers[index] === q.answer) {

            correct++;

            subjectStats[q.subject].correct++;
        }

    });

    const wrong =
        questions.length - correct - unanswered;

    const percentage =
        Math.round((correct / questions.length) * 100);


    document.getElementById("finalScore").textContent =
        `${correct} / ${questions.length}`;

    document.getElementById("percentage").textContent =
        `${percentage}%`;

    document.getElementById("correctAnswers").textContent =
        correct;

    document.getElementById("wrongAnswers").textContent =
        wrong;

    document.getElementById("unanswered").textContent =
        unanswered;


    let message = "";

    if (percentage >= 80) {

        message =
            "Excellent performance. Continue practising.";

    } else if (percentage >= 60) {

        message =
            "Good performance. More practice can improve your score.";

    } else if (percentage >= 40) {

        message =
            "Fair performance. Review the corrections and practise again.";

    } else {

        message =
            "Keep practising. Review the explanations and try again.";

    }

    document.getElementById("resultMessage").textContent =
        message;


    /* SUBJECT RESULTS */

    const subjectResults =
        document.getElementById("subjectResults");

    subjectResults.innerHTML = "";

    Object.keys(subjectStats).forEach(subject => {

        const stats = subjectStats[subject];

        const subjectPercentage =
            Math.round(
                (stats.correct / stats.total) * 100
            );

        subjectResults.innerHTML += `
            <div class="stat">
                <span>${subject}</span>
                <strong>
                    ${stats.correct}/${stats.total}
                    (${subjectPercentage}%)
                </strong>
            </div>
        `;

    });


    examScreen.classList.add("hidden");

    resultScreen.classList.remove("hidden");

    reviewScreen.classList.add("hidden");

    window.scrollTo(0, 0);
}


